UNIT_VALUE = re.compile(r"\s*[-+]?\d+(?:\.\d+)?\s*[A-Za-z%]+\s*")


def host_field_message(error):
    """InvalidField 转成读取路径上的中文报错，带修改建议。"""
    field = error.field
    if error.reason == "host_field_required":
        return f"缺少 {field}；" + ("填 user@address，或把 ssh 设为 local 以在本机派发。" if field == "ssh" else "请填写。")
    if field == "cache_dirs":
        return f"cache_dirs {error.detail}"
    if field == "platform":
        return "platform 必须是 macos、linux、posix 或 windows；本机目标（ssh 为 local）只支持 POSIX。"
    if field == "workdir":
        return "本机目标（ssh 为 local）的 workdir 必须是绝对路径或 ~ 开头；相对路径会随发起目录漂移。"
    if field in ("sync", "launcher", "enabled"):
        allowed = {"sync": "origin 或 direct", "launcher": "nohup 或 tmux", "enabled": "1、0、true、false、yes 或 no"}[field]
        return f"{field} 必须是 {allowed}。"
    shown = f"{field} = {error.detail!r}" if error.detail != "" else f"{field} 为空"
    if UNIT_VALUE.fullmatch(error.detail or ""):
        return f"{shown} 带了单位；请去掉单位，只写数字（例如 10）。"
    if field in ("max_heavy", "timeout"):
        return f"{shown} 无效；必须是不小于 1 的整数。"
    if field.endswith("_pct"):
        return f"{shown} 无效；必须是 0 到 100 之间的有限数。"
    return f"{shown} 无效；必须是有限的非负数（不接受 NaN、inf 和负数）；max_worktree_gb 留空或 0 表示不限。"


class HostConfigError(Exception):
    def __init__(self, message, code=4):
        super().__init__(message)
        self.code = code


class ConfigError(ValueError):
    """配置无效；strict 模式供 serve 重载时保留旧配置而不是退出进程。"""


class Config:
    strict = False  # 绕过 __init__ 构造的对象（测试替身）也按非 strict 处理

    def __init__(self, strict=False):
        self.strict = strict
        self.cp = configparser.ConfigParser(interpolation=None)
        if strict and os.path.exists(CONFIG):
            # cp.read silently skips unreadable files; a reload must not mistake
            # a transient EACCES for an empty configuration.
            with open(CONFIG, encoding="utf-8") as stream:
                self.cp.read_file(stream, CONFIG)
        else:
            self.cp.read(CONFIG, encoding="utf-8")
        self.loaded_at = messages.utc_now()

    def fail(self, message, code=1):
        if self.strict:
            raise ConfigError(message)
        die(message, code)

    def _section(self, kind, name):
        key = f"{kind}:{name}"
        return dict(self.cp[key]) if self.cp.has_section(key) else None

    def report_interval(self):
        value = os.environ.get("RD_REPORT_INTERVAL_SECONDS") or self.cp.get("monitor", "report_interval_seconds", fallback="900")
        try:
            interval = int(value)
        except (ValueError, TypeError):
            self.fail("RD_REPORT_INTERVAL_SECONDS / [monitor] report_interval_seconds must be a positive integer (seconds)", 4)
        if interval <= 0:
            self.fail("RD_REPORT_INTERVAL_SECONDS / [monitor] report_interval_seconds must be a positive integer (seconds)", 4)
        return interval

    def notify_channels(self):
        """[monitor] notify：启用的提醒通道；非法取值按配置错误退出 4。"""
        try:
            return notifier.parse(self.cp)
        except ValueError as error:
            self.fail(str(error), 4)

    def rollout_stats(self):
        """[features] rollout_stats：读取 Codex rollout 逐次调用用量，默认关闭；取值无效按关闭处理。"""
        return self.cp.get("features", "rollout_stats", fallback="false").strip().lower() in ("1", "true", "yes", "on")

    def scheduled_reclaim(self):
        """[features] scheduled_reclaim：serve 每小时回收已签收且过期的任务，超过 max_worktree_gb 再瘦身。
        默认开启，显式写 false 才关闭；取值无效按关闭处理。"""
        return self.cp.get("features", "scheduled_reclaim", fallback="true").strip().lower() in ("1", "true", "yes", "on")

    def warm_worktree(self):
        """[features] warm_worktree：命令任务热工作树，默认开启，显式写 false 整体关闭。"""
        return warm.feature_enabled(self.cp)

    def warm_idle_days(self):
        """热槽位闲置多少天后可回收；环境变量 RD_RETAIN_WARM_IDLE_DAYS 优先，默认 7。"""
        try:
            return warm.idle_days(self.cp)
        except ValueError as error:
            self.fail(str(error), 4)

    def line_enabled(self):
        """[features] line：显式写 false 才关闭；关闭后不接新线，已有线继续。"""
        return workline.feature_enabled(self.cp)

    def line_stale_days(self):
        """工作线停滞天数；环境变量 RD_LINE_STALE_DAYS 优先，默认 7。"""
        try:
            return workline.stale_days(self.cp)
        except ValueError as error:
            self.fail(str(error), 4)

    def retention_hours(self):
        """过期回收的保留时长（小时），从最后一次回执确认算起；环境变量优先。"""
        hours = {}
        for kind, default in RETENTION_HOURS.items():
            value = os.environ.get("RD_RETAIN_" + kind.upper() + "_HOURS") or self.cp.get("retention", kind + "_hours", fallback=str(default))
            try:
                hours[kind] = float(value)
            except (ValueError, TypeError):
                hours[kind] = -1
            if not hours[kind] >= 0:
                self.fail(f"RD_RETAIN_{kind.upper()}_HOURS / [retention] {kind}_hours 必须是非负小时数。", 4)
        return hours

    def recovery_limit(self):
        value = os.environ.get("RD_MAX_SAME_FAILURE_RESUMES") or self.cp.get("recovery", "max_same_failure_resumes", fallback="1")
        try:
            limit = int(value)
        except (ValueError, TypeError):
            self.fail("RD_MAX_SAME_FAILURE_RESUMES 必须是非负整数。", 4)
        if limit < 0:
            self.fail("RD_MAX_SAME_FAILURE_RESUMES 必须是非负整数。", 4)
        return limit

    def network_stall_seconds(self):
        value = os.environ.get("RD_NETWORK_STALL_SECONDS") or self.cp.get("monitor", "network_stall_seconds", fallback="600")
        return health.positive_seconds(value, "RD_NETWORK_STALL_SECONDS / [monitor] network_stall_seconds")

    def host(self, name, *, check_disabled=False, lenient=False):
        """按名取目标机。启用的主机完整校验，配置无效时报错（退出码 4）；已停用的主机不校验。
        check_disabled=True（显式 --host 派单）时已停用的主机也校验。
        lenient=True 用于已登记的在途任务（job_host）：不校验字段，任务必须能继续被监控与收尾。"""
        try:
            return self._build_host(name, check_disabled=check_disabled, lenient=lenient)
        except HostConfigError as error:
            self.fail(str(error), error.code)

    def _build_host(self, name, *, check_disabled=False, lenient=False):
        sec = self._section("host", name)
        if sec is None:
            raise HostConfigError(f"no [host:{name}] in {CONFIG}", 1)
        h = dict(DEFAULTS)
        if self.cp.has_section("defaults"):
            h.update(self.cp["defaults"])
        h.update(sec)
        if not lenient and (host_checks.is_enabled(h["enabled"]) or check_disabled):
            try:
                host_checks.validate(h, lenient=True)  # 读取路径与 CRUD 共用同一套完整校验
            except host_checks.InvalidField as error:
                raise HostConfigError(f"[host:{name}] 配置无效：{host_field_message(error)}", 4) from None
        h["ssh_opts"] = with_ssh_multiplexing(h["ssh_opts"])
        if h["platform"] in ("macos", "linux"):
            h["platform"] = "posix"
        if h["platform"] == "windows":
            h["path"] = sec.get("path", "")
        h["rollout_stats"] = "1" if self.rollout_stats() else "0"
        h["name"] = name
        h["probe_agent"] = getattr(self, "probe_agent", "codex")
        return h

    def host_names(self):
        return [s.split(":", 1)[1] for s in self.cp.sections() if s.startswith("host:")]

    def hosts(self):
        """已启用且配置有效的目标机。一台主机的配置错误只影响它自己：无效的启用主机被排除（见 host_errors），
        已停用的主机不校验。"""
        result = []
        for name in self.host_names():
            try:
                h = self._build_host(name)
            except HostConfigError:
                continue
            if host_checks.is_enabled(h["enabled"]):
                result.append(h)
        return result

    def host_errors(self):
        """{主机名: 报错文本}：已启用但配置无效的目标机。"""
        errors = {}
        for name in self.host_names():
            try:
                self._build_host(name)
            except HostConfigError as error:
                errors[name] = str(error)
        return errors

    def project(self, name):
        section = self._section("project", name) or {}
        try:
            slim.parse_paths(section.get("regenerable_paths", ""))
        except ValueError as error:
            self.fail(f"[project:{name}] regenerable_paths {error}", 4)
        return section

    def agent(self, name):
        a = dict(AGENTS.get(name, {}))
        a.update(self._section("agent", name) or {})
        if "start" not in a:
            self.fail(f"unknown agent '{name}'. Built in: {', '.join(AGENTS)}; add [agent:{name}] to {CONFIG}")
        a.setdefault("session_regex", SESSION_RE)
        a.setdefault("bin", a["start"].split()[0])
        a["kind"] = name
        return a


