def lock_wait_seconds():
    """CLI 直接调用时等待 job 锁的上限秒数；RD_LOCK_WAIT_SECONDS 覆盖，0 表示不等。
    非数字、非有限数和负数一律按默认 60 秒。serve 子进程固定为 0。"""
    try:
        value = float(os.environ.get("RD_LOCK_WAIT_SECONDS", "60"))
    except ValueError:
        return 60.0
    return value if math.isfinite(value) and value >= 0 else 60.0


# 本进程当前持有任务锁的 job；锁不可重入，持锁的调用链用它判断可以直接写。
# 按进程而不是按线程记录，只用于单线程的 CLI 路径（serve 的多线程路径不使用）。
HELD_JOBS = set()


@contextlib.contextmanager
def wait_job_lock(job):
    """有界等待取得 job 锁；等待超过约 2 秒时向 stderr 提示一次。超时抛 JobBusy。"""
    def notify():
        print("派单正被其他操作占用，等待中…", file=sys.stderr, flush=True)
    total = lock_wait_seconds()
    lock = JobLock(STATE, job)
    if total <= 0:
        lock.acquire()
    else:
        started = time.monotonic()
        try:
            lock.acquire(wait=min(total, 2.0))
        except JobBusy:
            if total <= 2.0:
                raise
            notify()
            lock.acquire(wait=max(0.0, total - (time.monotonic() - started)))
    HELD_JOBS.add(job)
    try:
        yield lock
    finally:
        HELD_JOBS.discard(job)
        lock.release()


def locked_job(command):
    @functools.wraps(command)
    def run_locked(a, cfg):
        try:
            with wait_job_lock(a.job):
                return command(a, cfg)
        except JobBusy:
            die("round_in_progress: round in progress; another operation holds the job lock; retry after it finishes", 4)
    return run_locked


