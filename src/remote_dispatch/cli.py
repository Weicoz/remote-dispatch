    if not rows:
        print("没有无主派单。")
    for row in rows:
        pending = "；".join(f"第 {p['round']} 轮待收取，签收：rdispatch ack {row['job']} --round {p['round']} --receipt-id {p['receipt_id']}"
                            for p in row["pending_receipts"]) or "无待收取回执"
