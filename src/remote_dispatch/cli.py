def resume_job(a, cfg, rec, *, prompt=None, before_launch=None, rollback_stack=None):
    if getattr(a, "agent", None) and a.agent != rec.get("agent"):
        die("harness_change_not_allowed: 续跑不能换 harness；请另派一单。", 4)
    require_user()
    if not rec.get("user_id") or not (rec.get("profile") or rec.get("isolated")):
        die("resume_not_allowed: 旧任务未固定用户配置；查看、取回仍可用，续跑必须重新派单。", 4)
    if not rec.get("agent"):
        die("resume_not_allowed: only agent jobs can be resumed; start a new job for commands")
    host = job_host(cfg, rec)
    host["probe_agent"] = rec["agent"]
    host["probe_profile_fingerprint"] = (rec.get("profile") or {}).get("fingerprint")
    st = remote_state(host, [rec["job"]]).get(rec["job"], {})
    if st.get("state") in ("running", "starting"):
        die("round_in_progress: round in progress; rdispatch stop it first or wait", 4)
    if st.get("state") == "unreachable":
        die(f"resume_host_unavailable: job is unreachable on {host['name']}", 4)
    source_host = host
    moving = bool(getattr(a, "host", None) and a.host != rec["host"])
    if moving:
        host = scoped_host(cfg.host(a.host), rec["user_id"])
        host["probe_agent"] = rec["agent"]
    info = probe(host)
    why = assess(host, info)
    print(fmt_probe(host, info, why))
    if why and not a.force_host:
        reason = "resume_host_unavailable" if not info["reachable"] else "resume_resource_check_failed"
        die(f"{reason}: {host['name']} cannot take the session now ({'; '.join(why)}).", 3)
    agent = rec.get("agent_config") or cfg.agent(rec["agent"])
    session = a.session or rec.get("receiver_session") or find_session(source_host, rec, agent)
    if not session:
        die("resume_session_not_found: could not find the agent's session id in the logs; pass --session ID")
    known = rec.get("receiver_session") or (find_session(source_host, rec, agent) if rec.get("handoff_version") else None)
    if known and session != known:
        die("resume_session_mismatch: 续派必须复用原接收会话；指定 --session 与原会话不匹配。", 4)
    receipt = collect_result(cfg, rec, st) if rec.get("handoff_version") else None
    check_recovery(rec, receipt, a, cfg)
    if prompt is None:
        prompt = sys.stdin.read() if a.prompt_file == "-" else Path(a.prompt_file).read_text(encoding="utf-8")
    round_prompt = prompt
    if getattr(a, "new_context", False):
        rec.setdefault("context_history", []).append(dict(receiver_session=session, from_round=rec["rounds"],
                                                          receipt_id=receipt["receipt_id"], reason="context", at=messages.utc_now()))
        session = None
        prompt = ("原接收会话因上下文故障退役；沿用当前工作树、模型、员工配置和原授权，仅完成本轮剩余项。"
                  "旧失败和回执保留，不重复已完成工作。\n\n" + prompt)
    if getattr(a, "retry_after_repair", None):
        rec.setdefault("recovery_repairs", []).append(dict(from_round=rec["rounds"],
                                                           evidence=a.retry_after_repair, at=messages.utc_now()))
    if moving:
        target_profile = agent_preflight(host, rec["user_id"], rec["agent"], agent, auto_sync=False)
        if target_profile != rec.get("profile"):
            die("resume_profile_mismatch: 目标机用户配置与原派单不一致；先同步原配置。", 4)
        rec.setdefault("context_history", []).append(dict(receiver_session=session, from_round=rec["rounds"],
                                                          reason="host_changed", at=messages.utc_now()))
        session = None
        prompt = "续跑已更换目标机；沿用迁移工作树、原 harness 和授权，仅完成附言要求。\n\n" + prompt
    # 续跑沿用原权限档位；显式 --permission-mode 才改变并记入任务。
    permission = getattr(a, "permission_mode", None) or rec.get("permission_mode")
    command = agent_command(agent, a.model or rec.get("model"), a.effort or rec.get("effort"), session, permission)
    rec["permission_mode"] = permission
    rec["receiver_session"] = session
    rec["rounds"] += 1
    rec["session"] = session
    rec["model"] = a.model or rec.get("model")
    rec["effort"] = a.effort or rec.get("effort")
    check_controller(host, rec["user_id"])
    with contextlib.ExitStack() as operation:
        if moving:
            (rollback_stack if rollback_stack is not None else operation).enter_context(migrate_job(rec, source_host, host))
        checkpoint = native.request(host, "resume-checkpoint", dict(job=rec["job"]))
        if before_launch:
            before_launch()
        guard = rollback_launch(host, rec, checkpoint)
        if rollback_stack is not None:
            rollback_stack.enter_context(guard)
            guard = contextlib.nullcontext()
        with reviews.rollback_files([job_path(rec["job"])]), guard, events.transaction():
            rec["round_prompts"] = dict(rec.get("round_prompts", {}), **{str(rec["rounds"]): round_prompt})
            save_job(rec)
            launch(host, rec, rec["rounds"], command, prompt, a.timeout or host["timeout"])
    print(f"resumed {rec['job']} (round {rec['rounds']}, session {session or 'pending new context'})")


@contextlib.contextmanager
def rollback_launch(host, rec, checkpoint):
    """Keep the target checkpoint alive until the caller publishes its events."""
    try:
        yield
    except (Exception, SystemExit) as error:
        if checkpoint is not None:
            try:
                native.request(host, "resume-rollback", dict(job=rec["job"], round=rec["rounds"], checkpoint=checkpoint))
            except (Exception, SystemExit) as rollback_error:
                raise ValueError("resume_launch_failed: 启动失败且目标机回滚未确认；请核对目标机状态。") from rollback_error
        if isinstance(error, ValueError) and str(error).startswith("event_write_failed:"):
            raise
        raise ValueError("resume_launch_failed: 目标机启动失败；请核对目标机状态后重试。") from error


@contextlib.contextmanager
def migrate_job(rec, source, target):
    """Transfer only this job's worktree; retain the source for recovery."""
    data = dict(job=rec["job"], bare=rec["bare"], branch=rec["branch"])
    try:
        with tempfile.TemporaryFile() as archive:
            native.request(source, "resume-export", data, output=archive)
            archive.seek(0)
            imported = native.request(target, "resume-import", data, payload=archive)
    except (Exception, SystemExit) as error:
        raise ValueError("resume_transfer_failed: 无法迁移派单工作树；原目标机与轮次保留。") from error
    rec.setdefault("worker_history", []).append({key: rec[key] for key in
        ("host", "worker_root", "shared_root", "worker_platform", "worker_python", "sync") if key in rec})
    target["workdir"] = imported["root"]
    rec.update(host=target["name"], worker_root=target["workdir"], shared_root=target["shared_workdir"],
               worker_platform=target["platform"], worker_python=target["python"], sync="direct",
               auth_file=target[agents.SPECS[rec["agent"]]["auth_key"]], profile_script_uploaded=False)
    try:
        yield
    except (Exception, SystemExit, KeyboardInterrupt):
        # Only the worktree created by this import is eligible for rollback.
        native.request(target, "clean", dict(data, delete_branch=True))
        raise


def cmd_fetch(a, cfg):
    rec = load_job(a.job)
    host = job_host(cfg, rec)
    repo, b = rec["repo"], rec["branch"]
    spec = f"+refs/heads/{b}:refs/remotes/rd/{b}"
    if rec["sync"] == "origin":
        git(["fetch", "origin", spec], repo)
    elif host["platform"] == "windows":
        with tempfile.TemporaryDirectory() as temporary:
            bundle = Path(temporary) / "result.bundle"
            with bundle.open("wb") as stream:
                native.request(host, "fetch-bundle", {"bare": rec["bare"], "branch": b}, output=stream)
            git(["fetch", str(bundle), spec], repo)
    else:
        git(["fetch", scp_path(host, rec.get("bare", f"repos/{rec['project']}.git")), spec], repo, env=git_ssh_env(host))
    log = git(["log", "--oneline", f"{rec['base']}..rd/{b}"], repo).stdout.strip()
    print(f"fetched into rd/{b}")
    print(log if log else "(no commits on top of the dispatched base)")
    if log:
        print(f"review: git diff {rec['base'][:10]}..rd/{b}     take it: git merge --ff-only rd/{b}")


@locked_job
def cmd_stop(a, cfg):
    rec = load_job(a.job)
    host = job_host(cfg, rec)
    stopper = messages.identifier(getattr(a, "stopped_by", None) or initiator_session(a) or "cli", "停止者")
    before = job_states(cfg, [rec]).get(rec["job"], {})
    request = rec.get("stop_requests", {}).get(str(rec["rounds"]))
    if request is None and before.get("state") in ("running", "starting"):
        request = dict(stopped_by=stopper, via=getattr(a, "via", "cli"), requested_at=messages.utc_now())
        rec.setdefault("stop_requests", {})[str(rec["rounds"])] = request
        save_job(rec)
    # Keep the original actor across failures after the target has been killed.
    already_stopped = request and before.get("state") == "done" and str(before.get("exit")) == "143"
    if already_stopped:
        snapshot = before
        print("stopped or already finished")
    else:
        if before.get("state") == "unreachable":
            die("停止结果尚未确认；请核对 rdispatch status 后重试。", 4)
        if host["platform"] == "windows":
            native.request(host, "stop", {"job": rec["job"]})
            print("stopped or already finished")
        else:
            r = ssh(host, KILLTREE + f'; D="$ROOT/jobs/{rec["job"]}"; p=$(cat "$D/pid" 2>/dev/null); '
                    'if [ -n "$p" ] && kill -0 "$p" 2>/dev/null; then killtree "$p"; echo 143 > "$D/exit_code"; '
                    'echo stopped; else echo "not running"; fi')
            print(r.stdout.strip())
        snapshot = job_states(cfg, [rec]).get(rec["job"], {}) if request else before
    if not request:
        return
    if snapshot.get("state") == "done" and str(snapshot.get("exit")) != "143":
        # The round finished on its own while stop was reaching the target.
        rec["stop_requests"].pop(str(rec["rounds"]), None)
        save_job(rec)
        return
    if snapshot.get("state") != "done" or str(snapshot.get("exit")) != "143":
        die("停止结果尚未确认；请核对 rdispatch status 后重试。", 4)
    receipt = queries(cfg).result(rec, rec["rounds"], snapshot)
    if receipt.get("stopped_by") and queries(cfg).acknowledgement(rec, receipt):
        return
    stopper, stopped_at = request["stopped_by"], request["requested_at"]
    events.emit(STATE, "job.state_changed", events.job_data(rec, execution_state="done", executor_exit=143,
                stopped_by=stopper, stopped_at=stopped_at, suppress_push=True))
    receipt.update(executor_exit=143, stopped_by=stopper, stopped_at=stopped_at,
                   suppress_push=True, review_state="pending", needs_initiator_review=True)
    report = dict(receipt.get("report") or dict(schema=1, kind="result", job=rec["job"], round=rec["rounds"],
                                               checks="not_reported", summary="派单已主动停止，仍需验收。"))
    report.update(outcome="failed", updated_at=stopped_at)
    receipt["report"] = report
    receipt["receipt_id"] = query.receipt_id(receipt)
    persist_receipt(rec, receipt)
    acknowledge_receipt(rec, receipt, stopper, request["via"])


def backup_reports(host, rec):
    root = Path(os.environ.get("RD_REPORTS_DIR") or "~/.local/share/remote-dispatch/reports").expanduser().resolve()
    root.mkdir(parents=True, exist_ok=True)
    job = messages.job_id(rec["job"])
    destination = root / job
    if destination.exists():
        destination = root / (job + "-" + str(time.time_ns()))
    with tempfile.TemporaryDirectory(prefix=".reports-", dir=root) as temporary:
        staged = Path(temporary) / "reports"
        staged.mkdir()
        with tempfile.TemporaryFile() as archive:
            if host["platform"] == "windows":
                native.request(host, "reports-bundle", {"job": job}, output=archive)
            else:
                ssh(host, f'D="$ROOT/jobs/{job}/reports"; '
                          'if [ -L "$D" ]; then echo "reports is a symlink" >&2; exit 1; '
                          'elif [ -d "$D" ]; then tar -cf - -C "$D" .; '
                          'elif [ -e "$D" ]; then exit 1; else tar -cf - -T /dev/null; fi', stdout=archive)
            archive.seek(0)
            native.extract(archive, staged)
        staged.rename(destination)
    print(f"reports saved: {destination}")
    return str(destination)


def worktree_changes(host, rec):
    """实时读取 head 和完整路径，NUL 分隔保留空格、换行及重命名两端。"""
    if host["platform"] == "windows":
        info = native.request(host, "clean-check", {"job": rec["job"], "detailed": True})
        head, status = info["head"], info["status"]
    else:
        wt = '"$ROOT/wt/' + messages.job_id(rec["job"]) + '"'
        reply = ssh(host, f'head=$(git -C {wt} rev-parse HEAD) || exit 1; '
                          'printf "%s\\n" "$head"; '
                          f'GIT_OPTIONAL_LOCKS=0 git -C {wt} status --porcelain=v1 -z --untracked-files=all', check=False)
        if not reply or reply.returncode:
            raise ValueError("无法核验 worktree 的 head 与未提交内容")
        head, separator, status = reply.stdout.partition("\n")
        if not separator:
            raise ValueError("worktree 检查响应无效")
    paths = []
    entries = iter(status.split("\0"))
    for entry in entries:
        if not entry:
            continue
        if len(entry) < 4 or entry[2] != " ":
            raise ValueError("worktree 路径状态无效")
        paths.append(entry[3:])
        if "R" in entry[:2] or "C" in entry[:2]:
            original = next(entries, "")
            if not original:
                raise ValueError("worktree 重命名路径状态无效")
            paths.append(original)
    return head, paths


def pending_results(cfg, rec, snapshot):
    unlaunched = rec.get("dispatch_state") in ("preparing", "preparation_failed")
    if rec.get("handoff_version") and not unlaunched:
        receipt = collect_result(cfg, rec, snapshot)
        if not receipt or delivery(rec, receipt) != "received":
            return True
    for path in result_path(rec, 1).parent.glob("r*.json"):
        if re.fullmatch(r"r[0-9]+\.json", path.name):
            receipt = messages.read_json(path)
            if receipt and delivery(rec, receipt) != "received":
                return True
    return False


def last_activity(rec):
    """最后一次回执确认时间；旧任务没有回执时退回任务登记的更新时间。"""
    acks = [path.stat().st_mtime for path in result_path(rec, 1).parent.glob("r*.ack.json")]
    return max(acks) if acks else os.path.getmtime(job_path(rec["job"]))


def disk_low(host):
    """目标机可用磁盘低于 min_free_disk_gb 时收紧保留期；无法读取时按不紧张处理。"""
    if host["platform"] == "windows":
        return False
    reply = ssh(host, 'd="$ROOT"; [ -d "$d" ] || d="$HOME"; df -Pk "$d" | awk \'NR==2{printf "%d",$4/1048576}\'', check=False, timeout=30)
    free = num(reply.stdout.strip()) if reply and reply.returncode == 0 else None
    return free is not None and free < float(host["min_free_disk_gb"])


# 回收阻塞原因的稳定枚举值；可回收时 code 为 "ok"。新增值必须同步 docs/cache-retention.md。
BLOCK_RUNNING = "running"
BLOCK_PREPARING = "preparing"
BLOCK_UNREACHABLE = "unreachable"
BLOCK_NOT_FINISHED = "not_finished"
BLOCK_SOURCE_MISSING = "source_missing"
BLOCK_UNVERIFIABLE = "unverifiable"
BLOCK_ORPHAN = "worktree_orphan"
BLOCK_NOT_FETCHED = "not_fetched"
BLOCK_NOT_MERGED = "not_merged"
BLOCK_INTO_REQUIRED = "into_required"
BLOCK_REF_INVALID = "ref_invalid"
BLOCK_RECEIPT_PENDING = "receipt_pending"
BLOCK_DIRTY = "uncommitted"
BLOCK_PINNED = "pinned"
BLOCK_RETENTION = "retention_not_expired"
BLOCK_PLAN_REFERENCED = "plan_referenced"
RECLAIM_OK = "ok"


def merge_block_code(reason):
    """把 merge_check 的原因文本归入枚举值。"""
    for prefix, code in (("未取回", BLOCK_NOT_FETCHED), ("无法核验", BLOCK_UNVERIFIABLE), ("未合入", BLOCK_NOT_MERGED),
                         ("需指定 --into", BLOCK_INTO_REQUIRED), ("REF 不存在", BLOCK_REF_INVALID)):
        if reason.startswith(prefix):
            return code
    return BLOCK_UNVERIFIABLE


def reclaim_check(cfg, rec, snapshot, host, *, single=False, force=False, a=None, into=None, mode="merged"):
    """回收安全条件的唯一判定点，单个 clean 与批量清理共用。

    返回 (code, detail, head, reasons)：code 为 None 表示安全条件全部满足。
    single 对应 `rdispatch clean JOB`（可被 force 跳过部分检查）；批量按 mode 区分 merged / expired。
    reasons 是 merge_check 的原文，供保留期分级使用。"""
    state = snapshot.get("state")
    unlaunched = rec.get("dispatch_state") in ("preparing", "preparation_failed")
    if rec.get("project") and not (single and force):
        referrers = plans.PlanStore(STATE, rec.get("user_id") or require_user(), rec["project"]).referrers(rec["job"])
        if referrers:
            return BLOCK_PLAN_REFERENCED, "待派登记中后续工作项仍引用该派单：" + "、".join(referrers), None, []
    if single:
        if state == "running" or (state == "starting" and not unlaunched):
            return BLOCK_RUNNING, "the job is still running; rdispatch stop it first", None, []
        if state == "unreachable":
            return BLOCK_UNREACHABLE, f"{host['name']} is unreachable; nothing was removed", None, []
        if rec.get("handoff_version") and not force and not unlaunched:
            require_initiator(rec, a)
            receipt = collect_result(cfg, rec, snapshot)
            if not receipt or delivery(rec, receipt) != "received":
                return BLOCK_RECEIPT_PENDING, "先用 rdispatch result 收取结果，再用 rdispatch ack 确认；未交付回执不清理。", None, []
        if state == "missing" or force:
            return None, "", None, []
        j, b = rec["job"], rec["branch"]
        if host["platform"] == "windows":
            info = native.request(host, "clean-check", {"job": j})
            orphan, dirty, head = False, str(info["dirty"]), info["head"]
        else:
            w = f'"$ROOT/wt/{messages.job_id(j)}"'
            r = ssh(host, f'if [ ! -e {w} ] || [ "$(git -C {w} rev-parse --show-toplevel 2>/dev/null)" = "$(cd {w} && pwd -P)" ]; then '
                          f'echo "dirty=$(git -C {w} status --porcelain 2>/dev/null | wc -l | tr -d " ")"; '
                          f'echo "head=$(git -C {w} rev-parse HEAD 2>/dev/null)"; else echo orphan; fi', check=False)
            fields = dict(line.partition("=")[::2] for line in (r.stdout or "").splitlines())
            orphan = "orphan" in fields or r.stdout.strip() == "orphan"
            dirty, head = fields.get("dirty", "0"), fields.get("head", "")
        if orphan:
            return BLOCK_ORPHAN, (f"{j} 的 worktree 目录已不在 git worktree 登记中或无法读取，无法核验其中是否有未提交内容。"
                                  "确认可以丢弃后用 --force。"), head, []
        if dirty.strip() != "0":
            return BLOCK_DIRTY, f"{dirty.strip()} uncommitted file(s) in the remote worktree would be lost. Check them, or --force.", head, []
        if not Path(rec["repo"]).is_dir():
            return BLOCK_SOURCE_MISSING, f"源仓库不存在：{rec['repo']}；确认可以丢弃后用 --force。", head, []
        have = git(["rev-parse", "-q", "--verify", f"refs/remotes/rd/{b}"], rec["repo"], check=False).stdout.strip()
        if head and head != rec["base"] and head != have:
            return BLOCK_NOT_FETCHED, "the job has commits you have not fetched. Run rdispatch fetch first, or --force.", head, []
        return None, "", head, []
    if state == "running":
        return BLOCK_RUNNING, "任务运行中", None, []
    if state == "starting" or rec.get("dispatch_state") == "preparing":
        return BLOCK_PREPARING, "任务准备中或启动结果待核实", None, []
    if state not in ("done", "dead"):
        if state == "unreachable":
            return BLOCK_UNREACHABLE, "连接不可达", None, []
        return BLOCK_NOT_FINISHED, "未确认任务已结束", None, []
    if not Path(rec["repo"]).is_dir():
        return BLOCK_SOURCE_MISSING, f"源仓库不存在：{rec['repo']}", None, []
    try:
        head, paths = worktree_changes(host, rec)
        reasons = merge_check(rec, head, into)
    except (OSError, ValueError, SystemExit, subprocess.SubprocessError) as error:
        return BLOCK_UNVERIFIABLE, f"核验或清理失败，保留未删除内容与登记：{error}", None, []
    unsafe = [r for r in reasons if r.startswith(("未取回", "无法核验"))]
    if unsafe or (reasons and mode == "merged"):
        chosen = unsafe or reasons
        return merge_block_code(chosen[0]), "；".join(chosen), head, reasons
    try:
        if pending_results(cfg, rec, snapshot):
            return BLOCK_RECEIPT_PENDING, "结果回执待收取；先用 rdispatch result / rdispatch ack", head, reasons
    except (OSError, ValueError, SystemExit, subprocess.SubprocessError) as error:
        return BLOCK_UNVERIFIABLE, f"核验或清理失败，保留未删除内容与登记：{error}", head, reasons
    included = rec.get("include_paths", [])
    unexpected = [p for p in paths if not any(
        item == "." or p == item or p.startswith(item.rstrip("/") + "/") for item in included)]
    if unexpected:
        return BLOCK_DIRTY, f"存在非 --include 路径的未提交内容：{unexpected!r}", head, reasons
    return None, "", head, reasons


def retention_verdict(rec, head, reasons, activity, hours, now):
    """返回 (可回收, 说明, 阻塞码)。只判断复用可能性；未取回、未提交等安全条件由 reclaim_check 先行拦截。"""
    if rec.get("keep_until", 0) > now:
        return False, "已用 rdispatch keep 钉住，到 " + time.strftime("%Y-%m-%d %H:%M", time.localtime(rec["keep_until"])), BLOCK_PINNED
    if not rec.get("agent"):
        kind, label = "command", "命令任务不能续跑"
    elif head == rec["base"] or not reasons:
        kind, label = "accepted", "已合入或无新提交"
    else:
        kind, label = "unmerged", "已取回未合入（" + "；".join(reasons) + "）"
    age = (now - activity) / 3600
    if age < hours[kind]:
        return False, f"{label}，保留期 {hours[kind]:g} 小时，还剩 {hours[kind] - age:.1f} 小时", BLOCK_RETENTION
    return True, f"{label}，最后确认于 {age:.1f} 小时前，超过保留期 {hours[kind]:g} 小时", None


def cmd_clean_batch(a, cfg, mode):
    """--merged 只看合入；--expired 另按续跑可能性分级保留，过期才回收。两者共用 reclaim_check 的安全条件。"""
    if a.job or a.force or a.delete_branch or getattr(a, "discard_reports", False):
        die(f"--{mode} 不与 job、--force、--delete-branch 或 --discard-reports 混用。", 4)
    as_json = getattr(a, "json", False)
    if as_json and not getattr(a, "dry_run", False):
        die("--json 只能与 --dry-run 一起使用。", 4)
    recs = scoped_jobs(a, cfg)
    if not recs:
        print("[]" if as_json else "no jobs.")
        return
    states = job_states(cfg, recs)
    hours = cfg.retention_hours() if mode == "expired" else None
    pressure = {}
    now = time.time()
    rows = []

    def report(j, code, text, line):
        rows.append(dict(job=j, reclaimable=code == RECLAIM_OK, code=code, reason=text))
        if not as_json:
            print(line)

    for rec in recs:
        j = rec["job"]
        snapshot = states.get(j, {})
        try:
            host = job_host(cfg, rec)
            code, detail, head, reasons = reclaim_check(cfg, rec, snapshot, host, a=a, into=getattr(a, "into", None), mode=mode)
            if code:
                report(j, code, detail, f"skip {j} [{code}]: {detail}")
                continue
            note = "reports 将保存，分支保留"
            if mode == "expired":
                key = (rec["host"], rec.get("worker_root"))
                if key not in pressure:
                    pressure[key] = disk_low(host)
                limits = {k: min(v, RETENTION_LOW_DISK_HOURS[k]) for k, v in hours.items()} if pressure[key] else hours
                expired, note, code = retention_verdict(rec, head, reasons, last_activity(rec), limits, now)
                if pressure[key]:
                    note += "；目标机磁盘不足，保留期已收紧"
                if not expired:
                    report(j, code, note, f"keep {j} [{code}]: {note}")
                    continue
            if getattr(a, "dry_run", False):
                report(j, RECLAIM_OK, note, f"would clean {j} [{RECLAIM_OK}] ({note})")
            else:
                print(f"clean {j}: {note}")
                remove_job(a, rec, host)
        except (OSError, ValueError, SystemExit, subprocess.SubprocessError) as error:
            text = f"核验或清理失败，保留未删除内容与登记：{error}"
            report(j, BLOCK_UNVERIFIABLE, text, f"skip {j} [{BLOCK_UNVERIFIABLE}]: {text}")
    if as_json:
        print(json.dumps(rows, ensure_ascii=False, indent=2))


def cmd_clean_merged(a, cfg):
    return cmd_clean_batch(a, cfg, "merged")


def cmd_keep(a, cfg):
    rec = load_job(a.job)
    if rec.get("user_id") and rec["user_id"] != require_user():
        die("只能钉住当前 RD_USER_ID 的任务。", 4)
    if a.hours < 0:
        die("--hours 必须是非负数；0 表示取消钉住。", 4)
    if a.hours == 0:
        rec.pop("keep_until", None)
        print(f"{rec['job']}: 已取消钉住，按默认保留期判断。")
    else:
        rec["keep_until"] = time.time() + a.hours * 3600
        print(f"{rec['job']}: 钉住到 {time.strftime('%Y-%m-%d %H:%M', time.localtime(rec['keep_until']))}，rdispatch clean --expired 不回收。")
    save_job(rec)


def cmd_clean(a, cfg):
    if getattr(a, "merged", False) and getattr(a, "expired", False):
        die("--merged 与 --expired 只能选一个。", 4)
    if getattr(a, "merged", False):
        return cmd_clean_merged(a, cfg)
    if getattr(a, "expired", False):
        return cmd_clean_batch(a, cfg, "expired")
    if not a.job or getattr(a, "into", None) or getattr(a, "dry_run", False) or getattr(a, "project", None):
        die("请指定 job；--into、--dry-run 和范围筛选需要 --merged 或 --expired。", 4)
    rec = load_job(a.job)
    host = job_host(cfg, rec)
    j = rec["job"]
    st = remote_state(host, [j]).get(j, {})
    code, detail, _, _ = reclaim_check(cfg, rec, st, host, single=True, force=a.force, a=a)
    if code:
        die(detail, 4 if code == BLOCK_RECEIPT_PENDING else 1)
    remove_job(a, rec, host)


def remove_job(a, rec, host):
    """共用报告保存与删除过程，调用方负责各自的清理前置条件。"""
    j, b = rec["job"], rec["branch"]
    bare = rec.get("bare", f"repos/{rec['project']}.git")
    if not getattr(a, "discard_reports", False):
        try:
            rec["reports_backup"] = backup_reports(host, rec)
            save_job(rec)
        except (OSError, ValueError, SystemExit, tarfile.TarError) as error:
            die(f"reports 取回失败，远端与 job 登记均保留：{error}；重试或显式 --discard-reports。")
    delete_worker = a.delete_branch
    delete_origin = a.delete_branch
    if rec.get("dispatch_state"):
        delete_origin = a.delete_branch and rec.get("owns_origin_branch", False)
        if host["platform"] == "windows":
            owned = native.request(host, "branch-owned", {"job": j})
        else:
            owned = ssh(host, f'test -f "$ROOT/jobs/{j}/branch-created"', check=False).returncode == 0
        delete_worker = a.delete_branch and (rec.get("owns_worker_branch", False) or owned)
    if host["platform"] == "windows":
        native.request(host, "clean", {"job": j, "bare": bare, "branch": b, "delete_branch": delete_worker})
    else:
        drop = (f'if git -C "$ROOT/{bare}" show-ref --verify --quiet {shlex.quote("refs/heads/" + b)}; then '
                f'git -C "$ROOT/{bare}" branch -q -D {shlex.quote(b)} || exit 1; fi; ') if delete_worker else ""
        wt = f'"$ROOT/wt/{messages.job_id(j)}"'
        # 登记已丢失或目录不可读写时 worktree remove 会失败：恢复权限，仍失败则删目录并 prune。
        ssh(host, f'if [ -e {wt} ]; then '
                  f'git -C "$ROOT/{bare}" worktree remove --force {wt} 2>/dev/null || {{ '
                  f'chmod -R u+rwx {wt} 2>/dev/null; '
                  f'git -C "$ROOT/{bare}" worktree remove --force {wt} 2>/dev/null || {{ '
                  f'rm -rf {wt} && [ ! -e {wt} ] && git -C "$ROOT/{bare}" worktree prune; }}; }} || exit 1; fi; '
                  f'{drop}rm -rf "$ROOT/jobs/{j}"')
    if delete_origin and rec["sync"] == "origin":
        git(["push", "origin", "--delete", b], rec["repo"])
    os.remove(job_path(j))
    print(f"cleaned {j}" + (" and deleted branch " + b if delete_worker else f" (branch {b} kept; ownership not confirmed or deletion not requested)"))


