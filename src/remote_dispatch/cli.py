def push_task_branch(repo, destination, branch, sha, env=None):
    pushed = git(["push", "--porcelain", "--no-follow-tags", f"--force-with-lease=refs/heads/{branch}:",
                  destination, f"{sha}:refs/heads/{branch}"], repo, env=env)
