def local_repo(custom_path=None):
    cmd = ["git"]
    if custom_path:
        cmd.extend(["-C", str(custom_path)])
    cmd.extend(["rev-parse", "--show-toplevel"])
    p = run(cmd, check=False)
    if p.returncode != 0:
        target = f"'{custom_path}'" if custom_path else "current directory"
        die(f"run this inside the git repository you want to dispatch from, or pass -C/--dir (got: {target})")
    return str(Path(p.stdout.strip()).resolve())


