def probe(host):
    options = None
    if not is_local(host):
        options = health.network_options(host)
        if host.get("probe_profile_fingerprint"):
            options["profile_fingerprint"] = host["probe_profile_fingerprint"]
    uid = require_user()
    if host["platform"] == "windows":
        try:
            return dict(native.request(host, "probe", {"network_options": options, "user_id": uid,
                        "agent": host.get("probe_agent", "codex"), "env_file": host.get("env_file", "")},
                        timeout=25 + options["network_timeout_seconds"]), host=host["name"], reachable=True)
        except (ValueError, subprocess.TimeoutExpired):
            return {"host": host["name"], "reachable": False, "error": "Windows SSH、运行环境或资源探针失败"}
    r = ssh(host, PROBE, check=False, timeout=25)
    info = {"host": host["name"], "reachable": bool(r and r.returncode == 0)}
    if info["reachable"]:
        info.update(kv.split("=", 1) for kv in r.stdout.split() if "=" in kv)
        if not is_local(host):
            source = Path(HERE, "rd_health.py").read_text(encoding="utf-8")
            code = source + "\nimport sys\nprint(json.dumps(network_probe(json.loads(sys.argv[1]), sys.argv[2], sys.argv[3], sys.argv[4])))"
            # 与任务启动使用相同的远端环境文件，保留其代理环境；不输出文件内容。
            env_file = host.get("env_file", "")
            env = ('set -a; . ' + shlex.quote(env_file) + '; set +a; ') if env_file else ""
            if env_file.startswith("~/"):
                env = 'set -a; . "$HOME"/' + shlex.quote(env_file[2:]) + '; set +a; '
            script = env + "python3 -c " + shlex.quote(code) + " " + shlex.quote(json.dumps(options)) + ' "$SHARED_ROOT" ' + shlex.quote(uid) + " " + shlex.quote(host.get("probe_agent", "codex"))
            result = ssh(host, script, check=False, timeout=options["network_timeout_seconds"] + 10)
            try:
                network = json.loads(result.stdout) if result and result.returncode == 0 else None
                if not isinstance(network, dict) or not isinstance(network.get("ok"), bool):
                    raise ValueError()
                info["network"] = network
            except ValueError:
                info["network"] = {"ok": False, "checks": [], "error": "network probe unavailable/timeout (requires python3 and curl)"}
    else:
        info["error"] = ((r.stderr if r else "timeout") or "").strip().splitlines()[-1:] or ["unreachable"]
        info["error"] = info["error"][0]
    return info


def num(v):
    try:
        return float(v)
    except (TypeError, ValueError):
        return None


def assess(host, info):
    """Return a list of reasons this host should not take a new session."""
    if not info["reachable"]:
        return [f"unreachable: {info['error']}"]
    why = []
    network = info.get("network")
    if network is not None and not network.get("ok"):
        failures = [f"{item['kind']} {item['target']}: {item['error']}" for item in network.get("checks", []) if not item["ok"]]
        why.append("network unavailable: " + ("; ".join(failures) or network.get("error", "probe failed")))
    load, ncpu = num(info.get("load1")), num(info.get("ncpu"))
    if load is not None and ncpu and load / ncpu > float(host["max_load_per_core"]):
        why.append(f"load {load:.1f} on {int(ncpu)} cores")
    mem = num(info.get("memfree"))
    if mem is not None and mem < float(host["min_free_mem_pct"]):
        why.append(f"only {mem:.0f}% memory free")
    disk = num(info.get("disk"))
    if disk is not None and disk < float(host["min_free_disk_gb"]):
        why.append(f"only {disk:.0f} GB disk free")
    if info.get("os") == "Windows":
        cpu = num(info.get("cpu_pct"))
        if cpu is None:
            why.append("Windows CPU usage unknown")
        elif cpu > float(host["max_cpu_pct"]):
            why.append(f"CPU {cpu:.1f}%")
    if mem is None or disk is None:
        why.append("memory or disk probe unknown")
    return why


def mb(v):
    """探针的交换量（如 "18500.00M"）换算成 MB；取不到返回 None。"""
    return num(v[:-1]) if isinstance(v, str) and v.upper().endswith("M") else num(v)


def swap_io_mb_s(info):
    io = num(info.get("swapio"))
    return None if io is None else io / 1024


def notes(host, info):
    """不拦派单、只提示的情况。"""
    used = mb(info.get("swap"))
    if used is None or used / 1024 <= float(host["max_swap_used_gb"]):
        return []
    io = swap_io_mb_s(info)
    rate = "paging rate unknown" if io is None else f"paging {io:.1f} MB/s"
    return [f"swap {used / 1024:.1f} GB used ({rate}), not counted as busy"]


def probe_all(hosts):
    with concurrent.futures.ThreadPoolExecutor(max_workers=8) as ex:
        return list(zip(hosts, ex.map(probe, hosts)))


def fmt_probe(host, info, why):
    if not info["reachable"]:
        return f"{host['name']:<12} UNREACHABLE  {info['error']}"
    unk = lambda k, suf="": (info.get(k) or "?") + suf
    verdict = "ok" if not why else ("unavailable: " if info.get("network", {}).get("ok") is False else "busy: ") + "; ".join(why)
    cpu = "cpu " + unk("cpu_pct", "%") if info.get("os") == "Windows" else "load " + unk("load1") + "/" + unk("ncpu") + "c"
    if is_local(host):
        net = "skipped for local"
    else:
        network = info.get("network", {})
        net = ", ".join(f"{item['kind']} {item['target']}={'ok' if item['ok'] else item['error']}" for item in network.get("checks", [])) or network.get("error", "unknown")
    name = host["name"] + (" (本机)" if is_local(host) else "")
    io = swap_io_mb_s(info)
    hint = "".join(f"  (note: {n})" for n in notes(host, info))
    return (f"{name:<12} {cpu}  mem-free {unk('memfree', '%')}  "
            f"swap {unk('swap')} used/{unk('swapfree')} free io {'?' if io is None else f'{io:.1f}'}MB/s  "
            f"disk {unk('disk', 'G')}  sessions {unk('running')}  "
            f"heavy {unk('heavy')}/{host['max_heavy']}  network [{net}]  -> {verdict}{hint}")


