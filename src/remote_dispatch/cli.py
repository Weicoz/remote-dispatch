def die(msg, code=1):
    print(f"rdispatch: {msg}", file=sys.stderr)
    sys.exit(code)


def run(cmd, check=True, capture=True, **kw):
    p = subprocess.run(cmd, text=True, stdout=subprocess.PIPE if capture else None,
                       stderr=subprocess.PIPE if capture else None, **kw)
    if check and p.returncode != 0:
        die(f"command failed ({p.returncode}): {' '.join(map(str, cmd))}\n{(p.stderr or '').strip()}")
    return p


