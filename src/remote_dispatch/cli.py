def locked_job(command):
    @functools.wraps(command)
    def run_locked(a, cfg):
        try:
            with JobLock(STATE, a.job):
                return command(a, cfg)
        except JobBusy:
            die("round_in_progress: round in progress; another operation holds the job lock; retry after it finishes", 4)
    return run_locked


def job_path(job):
    return os.path.join(str(Path(STATE).resolve()), "jobs", job + ".json")


def save_job(rec):
    path = Path(STATE).resolve() / "jobs" / (messages.job_id(rec["job"]) + ".json")
    with events.write_transaction([path]):
        try:
            previous = json.loads(path.read_text(encoding="utf-8"))
        except FileNotFoundError:
            previous = None
        messages.atomic_json(path, rec, limit=None)
        data = events.job_data(rec)
        if previous is None:
            events.emit(STATE, "job.created", data)
        elif events.display_data("job.state_changed", events.job_data(previous)) != events.display_data("job.state_changed", data):
            events.emit(STATE, "job.state_changed", data)


def load_job(job):
    messages.job_id(job)
    try:
        with open(job_path(job), encoding="utf-8") as f:
            return json.load(f)
    except FileNotFoundError:
        die(f"unknown job '{job}'. See: rdispatch status")


def all_jobs():
    d = os.path.join(STATE, "jobs")
    names = sorted(f[:-5] for f in os.listdir(d) if f.endswith(".json")) if os.path.isdir(d) else []
    return [load_job(n) for n in names]


