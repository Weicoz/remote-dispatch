def tracked_files(repo, path):
    """仓库里与 path 相关的已跟踪文件：path 本身、其下全部文件，以及各级上级路径上的已跟踪文件。"""
    specs = [path] + [path.rsplit("/", i)[0] for i in range(1, path.count("/") + 1)]
    p = git(["ls-files", "-z", "--", *[":(literal)" + spec for spec in specs]], repo, check=False)
    return [name for name in p.stdout.split("\0") if name] if p.returncode == 0 else []


def local_artifact_guard(repo, path, is_dir):
    """拉回前的本地保护；返回 (状态, 说明)，None 表示可写。跟踪冲突跳过，符号链接/创建目录失败为错误。"""
    hits = artifacts.tracked_conflicts(tracked_files(repo, path), path)
    if hits:
        return "skipped", f"本地目标已被 Git 跟踪（{hits[0]}），为免覆盖源码已跳过"
    dest = os.path.join(repo, *path.split("/"))
    existing = dest
    while not os.path.lexists(existing):
        existing = os.path.dirname(existing)
    if os.path.commonpath([repo, os.path.realpath(existing)]) != repo or (os.path.islink(dest) and is_dir):
        return "error", "本地目标路径经符号链接指向仓库外，已拒绝"
    try:
        os.makedirs(os.path.dirname(dest), exist_ok=True)
    except OSError as error:
        return "error", str(error)
    return None


ARTIFACT_FETCH_TIMEOUT = 1800  # 手动 fetch --artifacts
ARTIFACT_AUTO_TIMEOUT = 300  # 自动拉取（serve 轮询、result、wait）：有界，超时保持待拉，可用 fetch --artifacts 重试


def pull_artifacts(cfg, rec, timeout=ARTIFACT_FETCH_TIMEOUT):
    """把远端 worktree 里声明的产物拉回本地仓库同一相对路径；缺失单独报告，不算整体失败。
    POSIX 用 rsync；Windows 经原生 worker 的 base64 通道取 tar（与 fetch-bundle 同一通道，不依赖 scp 路径转换）。
    状态：fetched/missing/skipped 是终态，error 保持待拉可重试。结果写进 rec["artifacts_state"]。"""
    paths = rec.get("artifact_paths") or []
    host = job_host(cfg, rec)
    job, repo = rec["job"], os.path.realpath(rec["repo"])
    results = []
    kinds = {}
    try:
        if host["platform"] == "windows":
            kinds = native.request(host, "artifact-kinds", {"job": job, "paths": paths}) or {}
        else:
            probe = "".join(f'if [ -d {shlex.quote(p)} ]; then echo "d {p}"; elif [ -e {shlex.quote(p)} ]; then echo "f {p}"; '
                            f'else echo "m {p}"; fi\n' for p in paths)
            # 热槽位代次不一致（已被后来的任务接手）时 WT 为空：不拉，避免拉到别的任务的文件。
            r = ssh(host, warm.resolve_sh(rec) + 'if [ -z "$WT" ]; then echo T; exit 0; fi\n'
                          f'cd "$WT" 2>/dev/null || {{ echo W; exit 0; }}\n{probe}', check=False, timeout=60)
            if r is not None and r.returncode == 0:
                for line in r.stdout.splitlines():
                    if line == "T":
                        kinds = {p: "t" for p in paths}
                        break
                    if line == "W":
                        kinds = {p: "w" for p in paths}
                        break
                    kind, _, path = line.partition(" ")
                    kinds[path] = kind
    except (OSError, ValueError, SystemExit, subprocess.SubprocessError):
        kinds = {}
    for path in paths:
        kind = kinds.get(path)
        if kind is None:
            results.append(dict(path=path, status="error", error="无法连接目标机核对路径"))
        elif kind == "x":
            results.append(dict(path=path, status="error", error="目标机路径含符号链接或越界，已拒绝"))
        elif kind == "t":
            results.append(dict(path=path, status="skipped", error="工作树已被后来的任务接手，产物不可再拉"))
        elif kind in ("m", "w"):
            results.append(dict(path=path, status="missing", error="目标机 worktree 里没有该路径"))
        else:
            guard = local_artifact_guard(repo, path, kind == "d")
            if guard:
                results.append(dict(path=path, status=guard[0], error=guard[1]))
            elif host["platform"] == "windows":
                results.append(native_artifact(host, job, repo, path, kind == "d", timeout))
            else:
                results.append(rsync_artifact(host, job, repo, path, kind == "d", timeout, worktree=warm.job_worktree(rec)))
    number = rec.get("rounds") or 1
    state = dict(round=number, paths=list(paths), results=results, at=time.strftime("%Y-%m-%d %H:%M:%S"))
    rec["artifacts_state"] = state  # 最近一次；按轮次的状态在 artifacts_rounds
    rec.setdefault("artifacts_rounds", {})[str(number)] = state
    save_job(rec)
    if warm.is_warm(rec) and host["platform"] != "windows" and not artifacts.artifacts_pending(rec):
        # 产物已处理完，解除目标机上的钉住标记，槽位可被接手。
        ssh(host, warm.pin_script(rec, artifacts=False), check=False, timeout=30)
    return results


def native_artifact(host, job, repo, path, is_dir, timeout=ARTIFACT_FETCH_TIMEOUT):
    """Windows：worker 打 tar，本地校验成员后解到临时目录再替换；失败记 error，保持可重试。"""
    dest = os.path.join(repo, *path.split("/"))
    try:
        with tempfile.TemporaryDirectory(dir=os.path.dirname(dest)) as temporary:
            bundle = Path(temporary) / "artifact.tar"
            with bundle.open("wb") as stream:
                native.request(host, "fetch-artifact", {"job": job, "relative": path}, output=stream, timeout=timeout)
            staged = Path(temporary) / "staged"
            staged.mkdir()
            with tarfile.open(bundle) as archive:
                for member in archive.getmembers():
                    if not (member.isfile() or member.isdir()) or not artifacts.safe_member(member.name):
                        return dict(path=path, status="error", error=f"目标机回传了不安全的条目：{member.name}")
                archive.extractall(staged, filter="data") if sys.version_info >= (3, 12) else archive.extractall(staged)
            if is_dir:
                os.makedirs(dest, exist_ok=True)
                shutil.copytree(staged, dest, dirs_exist_ok=True)
            else:
                shutil.copy2(staged / os.path.basename(dest), dest)
    except (OSError, ValueError, tarfile.TarError, SystemExit, subprocess.SubprocessError) as error:
        return dict(path=path, status="error", error=f"Windows 产物取回失败：{error}"[:300])
    files, size = artifacts.local_size(dest)
    return dict(path=path, status="fetched", type="dir" if is_dir else "file", files=files, bytes=size)


def rsync_supports_protect_args():
    try:
        p = subprocess.run(["rsync", "--help"], capture_output=True, text=True, timeout=10)
    except (OSError, subprocess.TimeoutExpired):
        return False
    return "--protect-args" in (p.stdout or "") + (p.stderr or "")


def rsync_artifact(host, job, repo, path, is_dir, timeout=ARTIFACT_FETCH_TIMEOUT, worktree=None):
    dest = os.path.join(repo, *path.split("/"))
    source = scp_path(host, f"{worktree or 'wt/' + job}/{path}")
    command = ["rsync", "-a", "--safe-links"]
    if not is_local(host):
        command += ["-e", "ssh " + host["ssh_opts"]]
        prefix = host["ssh"] + ":"
        if rsync_supports_protect_args():
            command.append("-s")  # --protect-args：远端路径不经 shell 拆词
        elif source.startswith(prefix):
            # openrsync/旧 rsync 把远端路径交给远端 shell，手工加引号防空格拆词。
            source = prefix + shlex.quote(source[len(prefix):])
    command += ["--", source + "/", dest + "/"] if is_dir else ["--", source, dest]
    try:
        p = subprocess.run(command, capture_output=True, text=True, timeout=timeout)
    except subprocess.TimeoutExpired:
        return dict(path=path, status="error", error=f"rsync 超过 {timeout} 秒未完成，保持待拉；可用 fetch --artifacts 重试")
    except OSError as error:
        return dict(path=path, status="error", error=f"rsync 无法完成：{error}")
    if p.returncode:
        return dict(path=path, status="error", error=f"rsync 退出码 {p.returncode}：{(p.stderr or '').strip()[:200]}")
    files, size = artifacts.local_size(dest)
    return dict(path=path, status="fetched", type="dir" if is_dir else "file", files=files, bytes=size)


def auto_pull_artifacts(cfg, rec, snapshot):
    """任务已结束且尚未成功拉回时自动拉取一次；返回结果列表，无产物或不适用返回 None。"""
    if not rec.get("artifact_paths") or snapshot.get("state") not in ("done", "dead"):
        return None
    if artifacts.artifacts_pending(rec) or not artifacts.round_state(rec).get("results"):
        try:
            return pull_artifacts(cfg, rec, ARTIFACT_AUTO_TIMEOUT)
        except (OSError, SystemExit, subprocess.SubprocessError) as error:
            print(f"产物拉回未完成：{error}；稍后用 rdispatch fetch {rec['job']} --artifacts 重试。", file=sys.stderr)
            return None
    return artifacts.round_state(rec)["results"]


def release_unstarted_slot(host, rec):
    """准备或启动失败时释放热槽位领用：目标机上没有 pid 也没有 run 脚本（任务肯定没启动）才释放，
    释放后心跳随之停止；有则保留（启动结果待核实）。释放失败不掩盖原错误，控制端崩溃由心跳上限兜底。"""
    if warm.is_warm(rec) and host["platform"] != "windows":
        with contextlib.suppress(Exception, SystemExit):
            ssh(host, warm.release_unstarted_script(rec), check=False, timeout=30)


def place_worktree(cfg, host, rec, a, proj, repo_key, prefix):
    """POSIX 目标建任务 worktree：命令任务先试热槽位（一次 ssh 完成准备、领用、交接快照与精确快照），
    无空闲槽位且达上限、关闭热模式或领用结果缺失时建冷 worktree。结果写进 rec["worktree"] 并落盘。"""
    job, bare, branch = rec["job"], rec["bare"], rec["branch"]
    cold = f'git -C "$ROOT/{bare}" worktree add -q "$ROOT/wt/{job}" {shlex.quote(branch)} || exit 92'
    fields, prepared = None, False
    try:
        use_warm = warm.eligible(a, proj, host, cfg.warm_worktree())
        slots = warm.slot_limit(proj) if use_warm else 0
    except ValueError as error:
        die(str(error), 4)
    if use_warm:
        pinned = warm.pinned_jobs([r for r in all_jobs() if r.get("host") == host["name"]
                                   and r.get("user_id") == rec.get("user_id") and r["job"] != job], time.time())
        script = warm.claim_script(prefix, bare, job, branch, f"{warm.slot_name_part(rec['project'])}-{repo_key}", slots, pinned,
                                   heartbeat_max=warm.heartbeat_limit(getattr(a, "timeout", None) or host["timeout"],
                                                                      fingerprint_settings(proj)[1]))
        fields, prepared = warm.parse_result(ssh(host, script).stdout), True
        if fields and fields["mode"] == warm.COLD:
            print(f"热工作树：{fields.get('reason', '无空闲槽位')}，改用冷 worktree。")
        elif fields:
            print(f"热工作树：槽位 {fields['slot']}（" + ("复用" if fields.get("reused") == "1" else "新建") + "）")
    if not prepared:
        ssh(host, prefix + cold)
    elif fields is None:
        ssh(host, cold)
    warm.apply_result(rec, fields, job)
    save_job(rec)
    if warm.is_warm(rec) and rec.get("artifact_paths"):
        # 产物在槽位里：拉回前其他控制端的领用也不能接手。
        ssh(host, warm.pin_script(rec, artifacts=True))


def cmd_run(a, cfg):
    scope = run_scope(a, cfg)
    uid, forwarded_origin, origin_harness, owner = scope.uid, scope.forwarded_origin, scope.origin_harness, scope.owner
    repo, project, origin_url, proj = scope.repo, scope.project, scope.origin_url, scope.proj
    plan_item, after, plan_store = scope.plan_item, scope.after, scope.plan_store
    test_full = getattr(a, "test_full", False)
    if a.test or test_full:
        # 旧 test 视同 test_full；--test 优先快测，没配快测时回落到全量。
        full = proj.get("test_full") or proj.get("test")
        a.cmd = (full if test_full else proj.get("test_quick") or full) or die(
            f"--test-full needs 'test_full = <command>' (or 'test')" if test_full
            else f"--test needs 'test_quick', 'test_full' or 'test = <command>'"
            f" under [project:{project}] in {CONFIG}")
        a.heavy = a.heavy or test_full or proj.get("test_heavy", "true").lower() in ("1", "true", "yes")
    if bool(a.agent) == bool(a.cmd):
        die("give exactly one of --agent (with --prompt-file) or --cmd / --test")
    cfg.probe_agent = a.agent or "command"
    prompt = None
    permission = getattr(a, "permission_mode", None)
    if a.agent:
        try:
            spec = agents.spec(a.agent)
        except ValueError as error:
            die(str(error), 4)
        if not a.prompt_file:
            die("--agent needs --prompt-file")
        agent = cfg.agent(a.agent)
        if any("{model_args}" not in agent.get(k, "") for k in ("start", "resume")):
            die(f"{a.agent} 启动与续跑模板必须保留 {{model_args}}，以执行员工配置隔离与参数。", 4)
        # 参数错误在推分支、建 worktree 之前暴露。
        agent_command(agent, a.model, a.effort, permission=permission)
        prompt = sys.stdin.read() if a.prompt_file == "-" else Path(a.prompt_file).read_text(encoding="utf-8")
    elif permission:
        die("--permission-mode 只用于代理派单。", 4)
    if getattr(a, "context_from", None):
        if not a.agent:
            die("--context-from 只用于代理派单。", 4)
        prompt = context_pack(cfg, uid, a.context_from) + "\n" + prompt

    include_paths = include_list(a, repo)
    try:
        artifact_paths = artifacts.parse_artifacts(getattr(a, "artifact", None))
    except ValueError as error:
        die(str(error), 4)
    for artifact_path in artifact_paths:
        hits = artifacts.tracked_conflicts(tracked_files(repo, artifact_path), artifact_path)
        if hits:
            die(f"--artifact 不得指向已被 Git 跟踪的路径（会覆盖本地源码）：{artifact_path}（含 {hits[0]}）。"
                "已跟踪文件的改动走分支取回。", 4)
    line, no_line, line_hint = getattr(a, "line", None), getattr(a, "no_line", False), None
    if line and no_line:
        die("--line 与 --no-line 不能同时使用。", 4)
    if (getattr(a, "accept", None) or getattr(a, "accept_chain", False)) and not line:
        die("--accept、--accept-chain 需要同时指定 --line。", 4)
    if getattr(a, "accept_chain", False) and not getattr(a, "accept", None):
        die("--accept-chain 需要同时指定 --accept。", 4)
    if no_line:
        if not plan_item:
            die("--no-line 需要同时指定 --plan-item。", 4)
    elif line:
        if line_accept(a, cfg, scope, include_paths, prompt):
            return
    elif a.dispatch_mode == "line":
        if not plan_item:
            print("工作线未接线：line 模式需要 --plan-item；按默认方式派出。")
        elif line_wire(a, cfg, uid, owner, plan_store, plan_item, after, include_paths, prompt):
            return
    elif a.dispatch_mode == "suggest" and plan_item:
        wired, line_hint = line_ask(a, cfg, scope, include_paths, prompt)
        if wired:
            return
    sha = git(["rev-parse", "--verify", a.ref + "^{commit}"], repo).stdout.strip()
    source = git(["symbolic-ref", "--quiet", "HEAD"], repo, check=False)
    source_branch = source.stdout.strip()[len("refs/heads/"):] if source.returncode == 0 else None
    wip = b""
    if a.wip:
        diff = subprocess.run(["git", "-C", repo, "diff", "--no-ext-diff", "--no-textconv",
                               "--binary", "--full-index", "--src-prefix=a/", "--dst-prefix=b/", sha, "--"], capture_output=True)
        if diff.returncode:
            die("--wip 无法生成工作树补丁：" + diff.stderr.decode(errors="replace"))
        wip = diff.stdout
        if not wip:
            die(f"--wip：已跟踪文件相对 {a.ref} 没有改动；未跟踪文件请用 --include。未派单。", 4)
        print(f"wip: sending tracked working-tree changes relative to {a.ref}; applied to remote index")
    dirty = git(["status", "--porcelain", "-z", "-uall"], repo).stdout
    if dirty:
        unsent = unsent_changes(dirty, include_paths, wip=bool(a.wip))
        if unsent and (a.test or test_full) and not getattr(a, "allow_dirty", False):
            die("测试类派单（--test / --test-full）拒绝派出：本地有未发送的改动，远端会测到旧代码。\n  "
                + "\n  ".join(unsent[:5]) + ("\n  ..." if len(unsent) > 5 else "")
                + "\n先提交，或加 --wip（已跟踪文件改动）/ --include 路径（未跟踪文件）一并发送；"
                "确认要测 HEAD 时用 --allow-dirty 跳过。未派单。", 4)
        if unsent:
            print("警告：本地未提交的改动不会发送，远端运行的是 " + a.ref + " 的已提交代码"
                  "（先提交，或用 --wip / --include）。", file=sys.stderr)

    stamp = time.strftime("%Y%m%d-%H%M%S") + f"-{time.time_ns() % 1000000000:09d}"
    name = re.sub(r"[^A-Za-z0-9._-]+", "-", a.name or a.agent or "cmd").strip("-")
    job = f"{uid}-{project}-{name}-{stamp}"
    branch = a.branch or f"rd/{uid}/{name}-{stamp}"
    git(["check-ref-format", "--branch", branch], repo)
    fp_command, fp_timeout = fingerprint_settings(proj)
    skip_fp = bool(getattr(a, "skip_fingerprint", False))
    local_fp = None
    if fp_command and skip_fp:
        print("警告：已用 --skip-fingerprint 跳过环境指纹核对；本机与目标机环境可能不一致。", file=sys.stderr)
    elif fp_command:
        local_fp = run_local_fingerprint(fp_command, repo, fp_timeout)

    with contextlib.ExitStack() as stack:
        included = None
        if include_paths:
            included = stack.enter_context(tempfile.TemporaryFile())
            packed = subprocess.run(["tar", "-cf", "-", "-C", repo, "--", *include_paths],
                                    stdout=included, stderr=subprocess.PIPE,
                                    env=dict(os.environ, COPYFILE_DISABLE="1"))
            if packed.returncode:
                die("--include 打包失败，未派单：\n" + packed.stderr.decode(errors="replace"))
            included.seek(0)
            # 实际写入目标机的文件清单（任何 include 形式，含 "."），热槽位下次领用前据此清理。
            listing = subprocess.run(["tar", "-tf", "-"], stdin=included, capture_output=True)
            unpacked = warm.unpacked_files(listing.stdout.decode(errors="replace")) if listing.returncode == 0 else []
            included.seek(0)
        explicit = a.force_host and a.host not in (None, "auto")
        if explicit:
            candidates = [cfg.host(a.host, check_disabled=True)]
        elif fp_command and not skip_fp and a.host in (None, "auto"):
            candidates = pick_hosts(cfg, a.host, a.tag)
        else:
            candidates = [pick_host(cfg, a.host, a.tag)]
        remaining = candidates[1:]

        def bind_host(chosen):
            """目标机作用域、控制端检查与员工配置预检；首选与换机共用。"""
            chosen = scoped_host(chosen, uid)
            if getattr(a, "workdir", None):
                custom_root = a.workdir.rstrip("/\\")
                chosen["workdir"] = custom_root + ("/users/" + uid if uid else "")
                chosen["shared_workdir"] = custom_root
                if is_local(chosen) and not custom_root.startswith(("/", "~", "$HOME")):
                    die("本机目标的 --workdir 必须是绝对路径或 ~ 开头。", 4)
                try:
                    parse_cache_dirs(chosen.get("cache_dirs", ""), custom_root)
                except ValueError as error:
                    die(f"[host:{chosen['name']}] cache_dirs {error}", 4)
            check_controller(chosen, uid)
            if chosen["platform"] == "windows" and (a.test or test_full):
                a.cmd = proj.get("test_windows", a.cmd)
            return chosen, agent_preflight(chosen, uid, a.agent, agent) if a.agent else None

        def host_fields(chosen, chosen_profile):
            return {"host": chosen["name"], "sync": chosen["sync"], "worker_root": chosen["workdir"],
                    "shared_root": chosen["shared_workdir"], "profile": chosen_profile,
                    "auth_file": chosen[spec["auth_key"]] if a.agent else chosen["codex_auth_file"],
                    "worker_platform": chosen["platform"], "worker_python": chosen["python"]}

        host, profile = bind_host(candidates[0])
        rec = {"job": job, "project": project, "origin": origin_url, "repo": repo, "branch": branch,
               "base": sha, "source_branch": source_branch, "include_paths": include_paths,
               "agent": a.agent, "cmd": a.cmd, "rounds": 1,
               "created": time.strftime("%Y-%m-%d %H:%M:%S"), "user_id": uid,
               "model": a.model, "effort": a.effort, "agent_config": agent if a.agent else None,
               "agent_kind": a.agent, "isolated": bool(a.agent), "permission_mode": permission,
               "heavy": a.heavy,
               "handoff_version": 1, "initiator_session": owner, "test": bool(a.test or test_full),
               "test_tier": ("full" if test_full or not proj.get("test_quick") else "quick") if (a.test or test_full) else None,
               "regenerable_paths": slim.parse_paths(proj.get("regenerable_paths", ""))}
        rec["worktree"] = warm.cold_field(job)
        if include_paths:
            hashes = include_guard.hash_includes(repo, include_paths)
            if hashes is not None:
                rec["include_hashes"] = hashes
        rec.update(host_fields(host, profile))
        if artifact_paths:
            rec["artifact_paths"] = artifact_paths
        if fp_command and skip_fp:
            rec["fingerprint"] = {"command": fp_command, "skipped": True}
        if getattr(a, "gate", None):
            rec["gate"] = a.gate
        if plan_item:
            rec["plan_item"] = plan_item
        if line_hint:
            rec["line_hint"] = line_hint
        rec["round_prompts"] = {"1": prompt}
        source = dict(forwarded_origin) if forwarded_origin else initiators.origin(origin_harness, rec["created"])
        source["initiator_herdr"] = dict(source["initiator_herdr"], captured_at=rec["created"])
        rec.update(source)
        print(f"dispatching {job} -> {host['name']} (branch {branch}, base {sha[:10]}, sync {host['sync']})")

        repo_key = hashlib.sha256((origin_url or repo).encode()).hexdigest()[:12]
        rec["project_id"] = projects.project_id(project, origin_url)
        bare = f"repos/{project}-{repo_key}.git"
        rec["bare"] = bare
        rec["dispatch_state"] = "preparing"
        # 登记到 started 之间持有任务锁：并发的收取、清理等写操作拿不到锁，不会在半成品状态上落盘。
        stack.enter_context(wait_job_lock(job))
        projects.ProjectIndex(STATE, uid).register(rec)
        if plan_item:
            plan_store.attach_job(plan_item, job, after)
        tried = []
        while True:
            try:
                if host["platform"] == "windows":
                    rec["worktree"] = warm.cold_field(job)
                    native_init(host, rec, repo, sha, proj.get("origin_url") or origin_url)
                    if a.include:
                        native.request(host, "upload", {"relative": "wt/" + job, "archive": True}, payload=included)
                    if wip:
                        native.request(host, "apply-wip", {"job": job}, payload=wip)
                    setup = proj.get("setup_windows", proj.get("setup"))
                    if setup:
                        put_file(host, f"jobs/{job}/setup.ps1", setup)
                    spent = 0
                    if fp_command and not skip_fp:
                        spent = check_fingerprint(host, rec, host_fingerprint_command(proj, host, fp_command), local_fp,
                                                  fp_timeout, a.timeout or host["timeout"])
                    rec["dispatch_state"] = "launching"
                    save_job(rec)
                    launch(host, rec, 1, "", prompt, remaining_timeout(a.timeout or host["timeout"], spent))
                    rec["dispatch_state"] = "started"
                    save_job(rec)
                    record_decline(a, scope)
                    print(f"started. job id: {job}")
                    return
                if host["sync"] == "origin":
                    worker_url = proj.get("origin_url") or origin_url or die("this repository has no 'origin' remote")
                    if not rec.get("owns_origin_branch"):
                        push_task_branch(repo, "origin", branch, sha)
                        rec["owns_origin_branch"] = True
                        save_job(rec)
                    prep = (f'if [ -d "$ROOT/{bare}" ]; then\n'
                            f'  if git -C "$ROOT/{bare}" show-ref --verify --quiet {shlex.quote("refs/heads/" + branch)}; then '
                            f'echo "task branch already exists; use another --branch" >&2; exit 91; fi\n'
                            f'else GIT_TERMINAL_PROMPT=0 git clone --bare {shlex.quote(worker_url)} "$ROOT/{bare}" || exit 90; fi\n'
                            f'GIT_TERMINAL_PROMPT=0 git -C "$ROOT/{bare}" fetch origin '
                            f'{shlex.quote("refs/heads/" + branch + ":refs/heads/" + branch)} || exit 91\n'
                            f'touch "$ROOT/jobs/{job}/branch-created" || exit 91\n')
                elif host["sync"] == "direct":
                    ssh(host, f'mkdir -p "$ROOT/repos" && {{ [ -d "$ROOT/{bare}" ] || git init -q --bare "$ROOT/{bare}"; }}')
                    push_task_branch(repo, scp_path(host, bare), branch, sha, env=git_ssh_env(host))
                    rec["owns_worker_branch"] = True
                    save_job(rec)
                    prep = ""
                else:
                    die(f"[host:{host['name']}] sync must be origin or direct")
                place_worktree(cfg, host, rec, a, proj, repo_key,
                               f'mkdir -p "$ROOT/jobs/{job}" "$ROOT/repos" "$ROOT/wt" "$SHARED_ROOT/locks" "$ROOT/bin"\n{prep}')

                if a.include:
                    ssh(host, f'tar -xf - -C {warm.worktree_sh(rec)}', stdin=included)
                    if warm.is_warm(rec) and unpacked:
                        # 记下解包路径：下次领用前连被 .gitignore 忽略的文件一起清掉。
                        ssh(host, warm.record_unpacked_script(rec), stdin_data="\n".join(unpacked) + "\n")
                if wip:
                    with tempfile.TemporaryFile() as patch_file:
                        patch_file.write(wip)
                        patch_file.seek(0)
                        ssh(host, f'git -C {warm.worktree_sh(rec)} apply --index --binary -', stdin=patch_file)
                if proj.get("setup"):
                    put_file(host, f"jobs/{job}/setup.sh", proj["setup"] + "\n")
                spent = 0
                if fp_command and not skip_fp:
                    spent = check_fingerprint(host, rec, fp_command, local_fp, fp_timeout, a.timeout or host["timeout"])

                if a.agent:
                    cmd_text = agent_command(agent, a.model, a.effort, permission=permission)
                else:
                    cmd_text = ("rd-heavy sh -c " + shlex.quote(a.cmd)) if a.heavy else a.cmd
                rec["dispatch_state"] = "launching"
                save_job(rec)
                launch(host, rec, 1, cmd_text, prompt, remaining_timeout(a.timeout or host["timeout"], spent))
                rec["dispatch_state"] = "started"
                save_job(rec)
                record_decline(a, scope)
                print(f"started. job id: {job}")
                print(f"  rdispatch status {job}    rdispatch logs {job}    rdispatch wait {job}    rdispatch fetch {job}")
                break
            except FingerprintMismatch as mismatch:
                tried.append(mismatch.attempt)
                if not remaining:
                    reject_fingerprint(host, rec, fp_command, local_fp, tried)
                print(f"{host['name']} 环境指纹不一致，换下一台候选。", file=sys.stderr)
                drop_attempt(host, rec)
                host = remaining.pop(0)
                try:
                    host, profile = bind_host(host)
                except SystemExit:
                    rec["dispatch_state"] = "preparation_failed"
                    save_job(rec)
                    raise
                rec.update(host_fields(host, profile))
                rec["dispatch_state"] = "preparing"
                save_job(rec)
                print(f"dispatching {job} -> {host['name']} (branch {branch}, base {sha[:10]}, sync {host['sync']})")
                if included is not None:
                    included.seek(0)
                continue
            except (SystemExit, Exception, KeyboardInterrupt):
                if rec["dispatch_state"] == "fingerprint_rejected":
                    raise
                if rec["dispatch_state"] == "preparing":
                    rec["dispatch_state"] = "preparation_failed"
                    save_job(rec)
                    release_unstarted_slot(host, rec)
                    print(f"rdispatch: 准备失败，job 已登记：{job}；核对后用 rdispatch clean {job} --force --delete-branch 清理本任务。", file=sys.stderr)
                else:
                    release_unstarted_slot(host, rec)
                    print(f"rdispatch: 启动结果待核实，job 已登记：{job}；先用 rdispatch status {job} 检查。", file=sys.stderr)
                raise


def remote_state(host, jobs):
    if host["platform"] == "windows":
        try:
            return native.request(host, "state", {"jobs": jobs}, timeout=30)
        except (ValueError, subprocess.TimeoutExpired):
            return {j: {"state": "unreachable"} for j in jobs}
    sample_code = Path(HERE, "rd_health.py").read_text(encoding="utf-8") + "\nimport sys\nprint(json.dumps(log_sample(sys.argv[1], sys.argv[2])))"
    script = "sample_code=" + shlex.quote(sample_code) + "\nfor J in " + " ".join(map(shlex.quote, jobs)) + r'''; do
  D="$ROOT/jobs/$J"; st=missing
  if [ -d "$D" ]; then
    st=starting
    if [ -f "$D/exit_code" ]; then st=done
    elif [ -f "$D/pid" ] && kill -0 "$(cat "$D/pid")" 2>/dev/null; then st=running
    elif [ -f "$D/pid" ]; then st=dead; fi
  fi
  n=$(ls "$D"/run.r*.sh 2>/dev/null | sed 's/.*run.r//;s/\.sh$//' | sort -n | tail -n 1)
  n=${n:-0}
  last=$(tail -n 5 "$D/stdout.r$n.log" 2>/dev/null | awk 'NF{l=$0}END{print l}' | tr '\t' ' ' | cut -c1-200)
  head=$(cat "$D/head" 2>/dev/null); dirty=$(cat "$D/dirty" 2>/dev/null); head_source=recorded
  W="$ROOT/wt/$J"; [ -f "$D/worktree" ] && W=$(cat "$D/worktree")
  if [ "$st" = running ] && [ -d "$W" ]; then
    current_head=$(GIT_OPTIONAL_LOCKS=0 git -C "$W" rev-parse HEAD 2>/dev/null)
    if [ -n "$current_head" ]; then
      head=$current_head; head_source=live
      dirty=$(GIT_OPTIONAL_LOCKS=0 git -C "$W" status --porcelain 2>/dev/null | wc -l | tr -d ' ')
    fi
  fi
  # 热槽位被下一任务接手前写下的交接快照优先于记录值（槽位现场已不属于本任务）。
  if [ "$st" != running ] && [ -f "$D/final-head" ]; then head=$(cat "$D/final-head"); dirty=$(cat "$D/final-dirty" 2>/dev/null); head_source=recorded; fi
  setup=; [ -f "$D/setup.sh" ] && { [ -f "$D/setup.done" ] && setup=done || setup=pending; }
  sample=$(python3 -c "$sample_code" "$D" "$n" 2>/dev/null)
  printf '%s\t%s\t%s\t%s\t%s\t%s\t%s\t%s\t%s\t%s\t%s\t%s\t%s\t%s\n' "$J" "$st" "$(cat "$D/exit_code" 2>/dev/null)" \
    "$([ -f "$D/timed_out" ] && echo yes)" "$(cat "$D/push_rc" 2>/dev/null)" "$head" \
    "$dirty" "$n" "$setup" "$last" "$head_source" "$(date -u +%Y-%m-%dT%H:%M:%SZ)" "$sample" "$(cat "$D/started.r$n" 2>/dev/null)"
done'''
    r = ssh(host, script, check=False, timeout=30)
    out = {}
    if not r or r.returncode != 0:
        return {j: {"state": "unreachable"} for j in jobs}
    keys = ["job", "state", "exit", "timed_out", "push_rc", "head", "dirty", "round", "setup", "last", "head_source", "observed_at", "network_sample", "started_at"]
    for line in r.stdout.splitlines():
        parts = line.split("\t")
        if len(parts) == len(keys):
            out[parts[0]] = dict(zip(keys, parts))
            try:
                out[parts[0]]["network_sample"] = json.loads(parts[-2])
            except ValueError:
                out[parts[0]].pop("network_sample")
    return out


def job_states(cfg, recs):
    by_host = {}
    for r in recs:
        key = (r["host"], r.get("user_id"), r.get("worker_root"))
        if key not in by_host:
            by_host[key] = (job_host(cfg, r), [])
        by_host[key][1].append(r["job"])
    states = {}
    for host, jobs in by_host.values():
        states.update(remote_state(host, jobs))
    for rec in recs:
        state = states.get(rec["job"], {})
        if rec.get("dispatch_state") == "preparation_failed" and state.get("state") in ("starting", "missing"):
            state["state"] = "dead"
    return states


def describe(rec, st):
    s = st.get("state", "?")
    bits = [f"{rec['job']}  [{rec['host']}]  {s}"]
    if rec.get("user_id"):
        bits.append("ID=" + rec["user_id"])
    if rec.get("dispatch_state") == "preparation_failed":
        bits.append("preparation failed; registered for rdispatch clean")
    if s == "done":
        code = st.get("exit")
        label = {"0": "ok", "124": "timed out", "97": "setup failed", "95": "environment fingerprint mismatch", "98": "profile/auth setup failed", "96": "worktree missing", "143": "stopped"}.get(code, "failed")
        bits.append(f"exit {code} ({label})")
        if rec.get("handoff_version"):
            bits.append("等待发起方收取与判断；检查状态以结果回执为准")
    if rec.get("artifact_paths"):
        bits.append("产物 " + ("待拉回" if artifacts.artifacts_pending(rec) else "已处理") + f"（{len(rec['artifact_paths'])} 项）")
        if artifacts.artifacts_pending(rec) and warm.is_warm(rec):
            bits.append(warm.ARTIFACT_PIN_TEXT)
    if st.get("setup") == "pending" and s == "running":
        bits.append("running setup")
    if st.get("head"):
        bits.append("no new commits" if st["head"] == rec["base"] else f"new commits (head {st['head'][:10]})")
    if st.get("dirty") not in (None, "", "0"):
        bits.append(f"{st['dirty']} uncommitted file(s) left in worktree")
    if rec["sync"] == "origin" and st.get("push_rc") not in (None, "", "0"):
        bits.append("PUSH FAILED (see: rdispatch logs JOB --file push.log)")
    line = "  ".join(bits)
    if s == "running" and st.get("last"):
        line += f"\n    last output: {st['last']}"
    return line


def scoped_jobs(a, cfg=None, *, include_legacy=False, by_project=False):
    """跨发起会话查当前员工；项目显式指定，否则在当前仓库内筛选。

    by_project：不指定 --project 时取当前仓库的项目 ID 选择派单（同项目其他 worktree 派出的派单也在内）。"""
    uid = require_user()
    recs = [load_job(a.job)] if getattr(a, "job", None) else all_jobs()
    recs = [r for r in recs if r.get("user_id") == uid or (include_legacy and not r.get("user_id"))]
    project = getattr(a, "project", None)
    if project:
        inferred = queries(cfg).jobs(recs, {}, user_id=uid)
        recs = [rec for rec, row in zip(recs, inferred) if row["project"] == project]
    directory = get_dir(a)
    if directory or not project:
        probe = run(["git", "-C", directory or os.getcwd(), "rev-parse", "--show-toplevel"], check=False)
        if probe.returncode == 0:
            repo = Path(probe.stdout.strip()).resolve()
            if by_project:
                if not project:
                    name = project_name(str(repo))[0]
                    inferred = queries(cfg).jobs(recs, {}, user_id=uid)
                    recs = [rec for rec, row in zip(recs, inferred) if row["project"] == name]
            else:
                recs = [r for r in recs if Path(r["repo"]).resolve() == repo]
        elif directory:
            die("指定目录不是 Git 仓库。", 4)
    return recs


def merge_check(rec, head, into):
    """只检查本地对象与祖先关系；不隐式 fetch，也不猜合入目标。"""
    ref = into or rec.get("source_branch")
    reasons = []
    target = None
    blocker = workline.merge_blocker(rec)
    if blocker:
        reasons.append("未合入：" + blocker)
    if not ref:
        reasons.append("需指定 --into")
    else:
        reference = ref if into else "refs/heads/" + ref
        resolved = git(["rev-parse", "-q", "--verify", "--end-of-options", reference + "^{commit}"], rec["repo"], check=False)
        if resolved.returncode:
            reasons.append(f"REF 不存在或不是提交：{ref}")
        else:
            target = resolved.stdout.strip()
    if not head:
        reasons.append("无法核验远端 head")
    elif head != rec["base"]:
        if not re.fullmatch(r"[0-9a-fA-F]{40}|[0-9a-fA-F]{64}", head) or git(["cat-file", "-e", head + "^{commit}"], rec["repo"], check=False).returncode:
            reasons.append("未取回")
        elif target:
            compared = git(["merge-base", "--is-ancestor", head, target], rec["repo"], check=False)
            if compared.returncode:
                reasons.append("未合入 " + ref if compared.returncode == 1 else "无法核验合入关系")
    return reasons


